// App icon foreground: one ink stroke (a looped "l" with a swash) made with perfect-freehand, as an Android vector path.
import { getStroke } from "perfect-freehand";
import fs from "node:fs";
const n = 140, pts = [];
for (let i = 0; i < n; i++) {
  const t = i / (n - 1);
  // a single ink wave across the safe zone, firmer in the middle
  const x = 27 + t * 54;
  const y = 57 - 13 * Math.sin(t * Math.PI * 1.75 + 0.35) + t * 4;
  pts.push([x, y, 0.25 + 0.7 * Math.sin(t * Math.PI)]);
}
const o = getStroke(pts, { size: 8.5, thinning: 0.6, smoothing: 0.5, streamline: 0.5, easing: (t) => Math.sin((t * Math.PI) / 2), simulatePressure: false, last: true });
const d = o.reduce((acc, [x0, y0], i, a) => { const [x1, y1] = a[(i + 1) % a.length]; acc.push(`${x0.toFixed(2)},${y0.toFixed(2)} ${((x0 + x1) / 2).toFixed(2)},${((y0 + y1) / 2).toFixed(2)}`); return acc; }, []);
const path = `M${o[0][0].toFixed(2)},${o[0][1].toFixed(2)} Q` + d.join(" ") + " Z";
const xs = o.map((p) => p[0]), ys = o.map((p) => p[1]);
console.log("bounds", Math.min(...xs).toFixed(1), Math.min(...ys).toFixed(1), Math.max(...xs).toFixed(1), Math.max(...ys).toFixed(1));
const vec = (color) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by site/tools/icon.mjs (perfect-freehand, same stroke maths as the app) -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="${color}" android:pathData="${path}" />
</vector>
`;
const res = new URL("../../app/src/main/res/", import.meta.url).pathname;
fs.mkdirSync(res + "drawable", { recursive: true }); fs.mkdirSync(res + "mipmap-anydpi-v26", { recursive: true });
fs.writeFileSync(res + "drawable/ic_launcher_foreground.xml", vec("#000000"));
fs.writeFileSync(res + "drawable/ic_launcher_monochrome.xml", vec("#FFFFFFFF"));
fs.writeFileSync(res + "mipmap-anydpi-v26/ic_launcher.xml", `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`);
fs.writeFileSync(res + "values/ic_launcher_colors.xml", `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">#EE4B2B</color>
</resources>
`);
// preview SVG (circle mask, like most launchers)
fs.writeFileSync("/tmp/claude-0/icon-preview.svg", `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="432" height="432"><defs><clipPath id="c"><circle cx="54" cy="54" r="40"/></clipPath></defs><g clip-path="url(#c)"><rect width="108" height="108" fill="#ee4b2b"/><path d="${path.replace(/,/g, " ")}" fill="#000"/></g></svg>`);
